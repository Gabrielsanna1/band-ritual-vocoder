FilmstripLookAndFeel::FilmstripLookAndFeel()
{
    // Set dark color scheme
    setColour (juce::Slider::textBoxTextColourId, juce::Colour (0xFFE0E0E0));
    setColour (juce::Slider::textBoxOutlineColourId, juce::Colours::transparentBlack);
    setColour (juce::Slider::textBoxBackgroundColourId, juce::Colour (0xFF252530));

    setColour (juce::Label::textColourId, juce::Colour (0xFFE0E0E0));

    setColour (juce::ComboBox::backgroundColourId, juce::Colour (0xFF252530));
    setColour (juce::ComboBox::textColourId, juce::Colour (0xFFE0E0E0));
    setColour (juce::ComboBox::outlineColourId, juce::Colour (0xFF3A3A45));
    setColour (juce::ComboBox::arrowColourId, juce::Colour (0xFFE0E0E0));

    setColour (juce::PopupMenu::backgroundColourId, juce::Colour (0xFF1A1A1F));
    setColour (juce::PopupMenu::textColourId, juce::Colour (0xFFE0E0E0));
    setColour (juce::PopupMenu::highlightedBackgroundColourId, juce::Colour (0xFF3A3A45));
    setColour (juce::PopupMenu::highlightedTextColourId, juce::Colours::white);

    setColour (juce::TextButton::buttonColourId, juce::Colour (0xFF252530));
    setColour (juce::TextButton::textColourOnId, juce::Colour (0xFFE0E0E0));
    setColour (juce::TextButton::textColourOffId, juce::Colour (0xFFE0E0E0));

    setColour (juce::ToggleButton::textColourId, juce::Colour (0xFFE0E0E0));
    setColour (juce::ToggleButton::tickColourId, juce::Colour (0xFF64D2FF));
    setColour (juce::ToggleButton::tickDisabledColourId, juce::Colour (0xFF3A3A45));

    setColour (juce::GroupComponent::outlineColourId, juce::Colour (0xFF3A3A45));
    setColour (juce::GroupComponent::textColourId, juce::Colour (0xFFE0E0E0));

    // Load filmstrip images
    loadFilmstrips();
}

void FilmstripLookAndFeel::loadFilmstrips()
{
    // Load from binary resources (generated by JUCE from CMakeLists.txt)
    bigKnob = juce::ImageCache::getFromMemory (BinaryData::hise_knob_big_png,
                                                BinaryData::hise_knob_big_pngSize);

    mediumKnob = juce::ImageCache::getFromMemory (BinaryData::hise_Knob_medium_png,
                                                   BinaryData::hise_Knob_medium_pngSize);

    smallKnob = juce::ImageCache::getFromMemory (BinaryData::hise_knob_small_png,
                                                  BinaryData::hise_knob_small_pngSize);

    // Verify images loaded correctly
    jassert (bigKnob.isValid());
    jassert (mediumKnob.isValid());
    jassert (smallKnob.isValid());
}

void FilmstripLookAndFeel::setKnobSize (KnobSize size)
{
    currentSize = size;
}

juce::Image& FilmstripLookAndFeel::getCurrentFilmstrip()
{
    switch (currentSize)
    {
        case Big:    return bigKnob;
        case Small:  return smallKnob;
        case Medium:
        default:     return mediumKnob;
    }
}

int FilmstripLookAndFeel::getCurrentFrameHeight() const
{
    switch (currentSize)
    {
        case Big:    return 180;
        case Small:  return 70;
        case Medium:
        default:     return 100;
    }
}

//==============================================================================
void FilmstripLookAndFeel::drawRotarySlider (juce::Graphics& g,
                                              int x, int y, int width, int height,
                                              float sliderPos,
                                              float /*rotaryStartAngle*/,
                                              float /*rotaryEndAngle*/,
                                              juce::Slider& /*slider*/)
{
    auto& filmstrip = getCurrentFilmstrip();

    if (! filmstrip.isValid())
    {
        // Fallback: draw a simple circle if filmstrip not loaded
        g.setColour (juce::Colours::darkgrey);
        g.fillEllipse ((float) x, (float) y, (float) width, (float) height);
        return;
    }

    const int frameHeight = getCurrentFrameHeight();
    const int frameWidth = filmstrip.getWidth();  // Use actual image width

    // Calculate which frame to show based on slider position
    // sliderPos is 0.0 to 1.0, map to frame 0 to numFrames-1
    int frameIndex = juce::jlimit (0, numFrames - 1,
                                    (int) (sliderPos * (float) (numFrames - 1) + 0.5f));

    // Extract single frame from filmstrip
    int srcY = frameIndex * frameHeight;
    auto frame = filmstrip.getClippedImage ({ 0, srcY, frameWidth, frameHeight });

    // Calculate destination rectangle - center the knob in available space
    float size = (float) juce::jmin (width, height);
    float destX = (float) x + ((float) width - size) * 0.5f;
    float destY = (float) y + ((float) height - size) * 0.5f;

    // Draw the single frame scaled to fit
    g.drawImage (frame,
                 juce::Rectangle<float> (destX, destY, size, size),
                 juce::RectanglePlacement::centred);
}

