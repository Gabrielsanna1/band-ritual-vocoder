//==============================================================================
void FilmstripLookAndFeel::drawComboBox (juce::Graphics& g, int width, int height,
                                          bool isButtonDown, int /*buttonX*/, int /*buttonY*/,
                                          int /*buttonW*/, int /*buttonH*/,
                                          juce::ComboBox& box)
{
    auto bounds = juce::Rectangle<int> (0, 0, width, height).toFloat();
    auto cornerSize = 4.0f;

    // Background
    g.setColour (box.findColour (juce::ComboBox::backgroundColourId));
    g.fillRoundedRectangle (bounds, cornerSize);

    // Border
    g.setColour (box.findColour (juce::ComboBox::outlineColourId));
    g.drawRoundedRectangle (bounds.reduced (0.5f), cornerSize, 1.0f);

    // Arrow area
    auto arrowZone = bounds.removeFromRight ((float) height).reduced (8.0f);

    // Draw selected item text
    auto textBounds = bounds.reduced (6.0f, 0.0f);
    g.setColour (box.findColour (juce::ComboBox::textColourId));
    g.setFont (juce::Font (height * 0.55f));
    g.drawText (box.getText(), textBounds.toNearestInt(), juce::Justification::centredLeft, true);

    // Draw arrow
    juce::Path arrow;
    arrow.addTriangle (arrowZone.getCentreX() - 4.0f, arrowZone.getCentreY() - 2.0f,
                       arrowZone.getCentreX() + 4.0f, arrowZone.getCentreY() - 2.0f,
                       arrowZone.getCentreX(), arrowZone.getCentreY() + 3.0f);

    g.setColour (box.findColour (juce::ComboBox::arrowColourId)
                     .withAlpha (isButtonDown ? 1.0f : 0.7f));
    g.fillPath (arrow);
}

//==============================================================================
void FilmstripLookAndFeel::drawPopupMenuItem (juce::Graphics& g, const juce::Rectangle<int>& area,
                                               bool isSeparator, bool isActive, bool isHighlighted,
                                               bool isTicked, bool /*hasSubMenu*/,
                                               const juce::String& text,
                                               const juce::String& /*shortcutKeyText*/,
                                               const juce::Drawable* /*icon*/,
                                               const juce::Colour* /*textColour*/)
{
    if (isSeparator)
    {
        auto r = area.reduced (5, 0);
        r.removeFromTop (r.getHeight() / 2 - 1);
        g.setColour (juce::Colour (0xFF3A3A45));
        g.fillRect (r.removeFromTop (1));
        return;
    }

    auto textColourToUse = findColour (juce::PopupMenu::textColourId);

    if (isHighlighted && isActive)
    {
        g.setColour (findColour (juce::PopupMenu::highlightedBackgroundColourId));
        g.fillRect (area);
        textColourToUse = findColour (juce::PopupMenu::highlightedTextColourId);
    }

    g.setColour (textColourToUse.withAlpha (isActive ? 1.0f : 0.5f));
    g.setFont (12.0f);

    auto textArea = area.reduced (8, 0);

    if (isTicked)
    {
        // Draw checkmark
        auto tickArea = textArea.removeFromLeft (textArea.getHeight());
        g.drawText (juce::CharPointer_UTF8 ("\xe2\x9c\x93"), tickArea,
                    juce::Justification::centred);
    }

    g.drawFittedText (text, textArea, juce::Justification::centredLeft, 1);
}

//==============================================================================
void FilmstripLookAndFeel::drawToggleButton (juce::Graphics& g, juce::ToggleButton& button,
                                              bool shouldDrawButtonAsHighlighted,
                                              bool /*shouldDrawButtonAsDown*/)
{
    auto bounds = button.getLocalBounds().toFloat();

    // Background
    auto bgColour = button.getToggleState()
                        ? juce::Colour (0xFF64D2FF).withAlpha (0.3f)
                        : juce::Colour (0xFF252530);

    if (shouldDrawButtonAsHighlighted)
        bgColour = bgColour.brighter (0.1f);

    g.setColour (bgColour);
    g.fillRoundedRectangle (bounds, 4.0f);

    // Border
    g.setColour (button.getToggleState()
                     ? juce::Colour (0xFF64D2FF)
                     : juce::Colour (0xFF3A3A45));
    g.drawRoundedRectangle (bounds.reduced (0.5f), 4.0f, 1.0f);

    // Text
    g.setColour (button.getToggleState()
                     ? juce::Colours::white
                     : juce::Colour (0xFFE0E0E0));
    g.setFont (11.0f);
    g.drawText (button.getButtonText(), bounds, juce::Justification::centred);
}

//==============================================================================
void FilmstripLookAndFeel::drawButtonBackground (juce::Graphics& g, juce::Button& button,
                                                  const juce::Colour& backgroundColour,
                                                  bool shouldDrawButtonAsHighlighted,
                                                  bool shouldDrawButtonAsDown)
{
    auto bounds = button.getLocalBounds().toFloat();
    auto cornerSize = 4.0f;

    auto baseColour = backgroundColour;

    if (shouldDrawButtonAsDown)
        baseColour = baseColour.brighter (0.2f);
    else if (shouldDrawButtonAsHighlighted)
        baseColour = baseColour.brighter (0.1f);

    g.setColour (baseColour);
    g.fillRoundedRectangle (bounds, cornerSize);

    g.setColour (juce::Colour (0xFF3A3A45));
    g.drawRoundedRectangle (bounds.reduced (0.5f), cornerSize, 1.0f);
}

//==============================================================================
juce::Font FilmstripLookAndFeel::getPopupMenuFont()
{
    return juce::Font (juce::FontOptions (12.0f));
}

void FilmstripLookAndFeel::getIdealPopupMenuItemSize (const juce::String& text, bool isSeparator,
                                                       int /*standardMenuItemHeight*/,
                                                       int& idealWidth, int& idealHeight)
{
    if (isSeparator)
    {
        idealHeight = 10;
        idealWidth = 50;
    }
    else
    {
        idealHeight = 22;  // Compact item height
        idealWidth = getPopupMenuFont().getStringWidth (text) + 24;
    }
}
